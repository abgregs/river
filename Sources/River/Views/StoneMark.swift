import CoreGraphics
import Foundation

/// River's mark (docs/design/stones-identity.md): three soft stones inspired by a bold
/// lowercase r, which morph into three level bars while River listens. One set of shapes
/// that every surface draws — the live indicator and the menu bar glyphs — so they match by
/// construction.
///
/// Shapes are in design units with y pointing down, as on the study page
/// (docs/design/studies/stones-motion.html): the stem is 126 wide, the baseline is at 521, and
/// the mark spans x 78…545, the bars' width.
enum StoneMark {
    typealias Point = SIMD2<Double>

    static let stem = 126.0
    static let baseline = 521.0
    // The union of the r at rest and the bars: what the panel fits.
    static let bounds = CGRect(x: 78, y: 0, width: 467, height: 521)

    // Three bars of the stem's width spread across the mark. At silence a bar is about as
    // tall as it is wide, a stone; at full level it reaches the r's x-height.
    static let barWidth = stem
    static let barGap = (bounds.width - 3 * stem) / 2
    static let barMinHeight = stem * 0.95
    static let barMaxHeight = 509.0
    // The pieces' own corner radius, and the 35° slant of the stem's cut on the bar tops.
    static let cornerRadius = (0.2 * stem).rounded()
    static let barSlant = tan(35 * Double.pi / 180)

    // Every outline is resampled to four sides of this many points, from the corners of its
    // bounding box, so a stone and its bar share one frame: each side of the stone becomes
    // the matching side of the bar instead of points sliding around the outline.
    static let pointsPerSide = 48

    /// The three stones at rest, left to right: the foot, the hook, the terminal.
    static let pieces: [[Point]] = outlineData.split(separator: "|").map { part in
        let points = part.split(whereSeparator: \.isWhitespace).map { pair in
            let xy = pair.split(separator: ",").map { Double($0)! }
            return Point(xy[0], xy[1])
        }
        return anchored(points, corners: boundingCorners(points))
    }

    /// How far the r at rest must move to share the bars' center. The r is narrower than the
    /// bars and sits to their right in the source glyph; the drawing slides the whole mark by
    /// this much less its morph progress, so it is centered at rest and as bars while the
    /// stones keep the relative motion the overlap test measures.
    static let restCentering = bounds.midX - boundingBox(pieces).midX

    /// Bar `index` at `level` (0 silence, 1 full), sampled in the same four-sided frame.
    static func bar(_ index: Int, level: Double) -> [Point] {
        let x0 = bounds.minX + Double(index) * (barWidth + barGap), x1 = x0 + barWidth
        let height = barMinHeight + (barMaxHeight - barMinHeight) * min(1, max(0, level))
        let rise = barSlant * barWidth / 2
        let corners = [Point(x0, baseline - height + rise), Point(x1, baseline - height - rise),
                       Point(x1, baseline), Point(x0, baseline)]
        let (points, middles) = fillet(corners, radius: cornerRadius)
        return (0..<4).flatMap { side in
            resampleArc(points, from: middles[side], to: middles[(side + 1) % 4], count: pointsPerSide)
        }
    }

    /// A stone partway to its bar. Sideways motion leads and growth lags: the foot and the hook
    /// start stacked in the stem's column, so moving both together grew the hook down into the
    /// foot before the foot had slid out of the way. Leading with x clears the column first;
    /// going back, growth unwinds first.
    static func blend(_ piece: [Point], _ bar: [Point], progress t: Double) -> [Point] {
        let tx = 1 - (1 - t) * (1 - t), ty = t * t
        return zip(piece, bar).map { p, b in Point(p.x + (b.x - p.x) * tx, p.y + (b.y - p.y) * ty) }
    }

    /// The transform that fits `region` (design units) into `rect`: uniform scale to the
    /// rect's height, centered.
    static func transform(fitting region: CGRect, into rect: CGRect) -> CGAffineTransform {
        let scale = min(rect.width / region.width, rect.height / region.height)
        return CGAffineTransform(translationX: rect.midX - region.midX * scale, y: rect.midY - region.midY * scale)
            .scaledBy(x: scale, y: scale)
    }

    static func path(_ points: [Point], transform: CGAffineTransform) -> CGPath {
        let path = CGMutablePath()
        path.addLines(between: points.map { CGPoint(x: $0.x, y: $0.y) }, transform: transform)
        path.closeSubpath()
        return path
    }

    static func boundingBox(_ outlines: [[Point]]) -> CGRect {
        let all = outlines.joined()
        let xs = all.map(\.x), ys = all.map(\.y)
        return CGRect(x: xs.min()!, y: ys.min()!, width: xs.max()! - xs.min()!, height: ys.max()! - ys.min()!)
    }

    // MARK: - Resampling

    private static func distance(_ a: Point, _ b: Point) -> Double { (a - b).length }

    private static func boundingCorners(_ points: [Point]) -> [Point] {
        let box = boundingBox([points])
        return [Point(box.minX, box.minY), Point(box.maxX, box.minY), Point(box.maxX, box.maxY), Point(box.minX, box.maxY)]
    }

    // Clockwise on screen (y down), from the points nearest the box's corners.
    private static func anchored(_ points: [Point], corners: [Point]) -> [Point] {
        let signedArea = points.indices.reduce(0.0) { sum, i in
            let a = points[i], b = points[(i + 1) % points.count]
            return sum + a.x * b.y - b.x * a.y
        }
        let ring = signedArea > 0 ? points : points.reversed()
        let anchors = corners.map { corner in ring.indices.min { distance(ring[$0], corner) < distance(ring[$1], corner) }! }
        return (0..<4).flatMap { side in
            resampleArc(ring, from: anchors[side], to: anchors[(side + 1) % 4], count: pointsPerSide)
        }
    }

    // `count` points spaced evenly by arc length along the closed outline from `start` up to
    // (not including) `end`.
    private static func resampleArc(_ ring: [Point], from start: Int, to end: Int, count: Int) -> [Point] {
        var arc: [Point] = []
        var k = start
        while true {
            arc.append(ring[k])
            if k == end { break }
            k = (k + 1) % ring.count
        }
        var lengths = [0.0]
        for i in 1..<arc.count { lengths.append(lengths[i - 1] + distance(arc[i - 1], arc[i])) }
        let total = lengths.last!
        var segment = 0
        return (0..<count).map { s in
            let target = total * Double(s) / Double(count)
            while segment < lengths.count - 2 && lengths[segment + 1] < target { segment += 1 }
            let span = lengths[segment + 1] - lengths[segment]
            let u = span > 0 ? (target - lengths[segment]) / span : 0
            return arc[segment] + (arc[segment + 1] - arc[segment]) * u
        }
    }

    // A polygon with every corner rounded to `radius` (or less where a side is too short),
    // and the index of each corner arc's middle point, which anchors the resampling.
    private static func fillet(_ polygon: [Point], radius: Double, steps: Int = 10) -> (points: [Point], middles: [Int]) {
        var points: [Point] = [], middles: [Int] = []
        for i in polygon.indices {
            let p = polygon[i], a = polygon[(i + polygon.count - 1) % polygon.count], c = polygon[(i + 1) % polygon.count]
            let la = distance(a, p), lc = distance(c, p)
            let u = (a - p) / la, v = (c - p) / lc
            let theta = acos(min(1, max(-1, (u * v).sum())))
            let d = min(radius / tan(theta / 2), la / 2, lc / 2)
            let r = d * tan(theta / 2)
            let t1 = p + u * d, t2 = p + v * d
            let bisector = u + v
            let center = p + bisector / bisector.length * (r / sin(theta / 2))
            let a1 = atan2(t1.y - center.y, t1.x - center.x)
            var delta = atan2(t2.y - center.y, t2.x - center.x) - a1
            while delta > .pi { delta -= 2 * .pi }
            while delta < -.pi { delta += 2 * .pi }
            for s in 0...steps {
                let angle = a1 + delta * Double(s) / Double(steps)
                points.append(center + Point(cos(angle), sin(angle)) * r)
                if s == steps / 2 { middles.append(points.count - 1) }
            }
        }
        return (points, middles)
    }

