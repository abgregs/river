// Writes the shipped mark's data as Swift, from kawa-motion-r1.json: each stroke's outline as
// cubic Béziers, its brush spine (top to tip), the mark's box and its halfway centring point.
// Usage: node kawa-swift.mjs > ../../../../Sources/River/Views/KawaMark+Outlines.swift
import fs from 'fs';

const data = JSON.parse(fs.readFileSync(new URL('./kawa-motion-r1.json', import.meta.url)));
const n = (v) => (Number.isInteger(v) ? `${v}.0` : String(v));
const rows = (values, per, indent) => {
  const out = [];
  for (let i = 0; i < values.length; i += per) out.push(indent + values.slice(i, i + per).map(n).join(', ') + ',');
  return out.join('\n');
};
const strokes = data.strokes.map(({ d, spine }) => {
  if (!/^M[^MZ]*Z$/.test(d.replace(/\s+/g, ' ').trim())) throw new Error('expected one closed subpath per stroke');
  const values = d.match(/-?\d*\.?\d+/g).map(Number);
  if ((values.length - 2) % 6) throw new Error('expected cubic segments only');
  return { values, spine: spine.flat().map((v) => Math.round(v * 10) / 10) };
});
const [x0, y0, x1, y1] = data.box;

process.stdout.write(`// Generated by docs/design/studies/kawa/kawa-swift.mjs from kawa-motion-r1.json. Do not edit by hand.

import CoreGraphics

extension KawaMark {
    /// Each stroke, left to right: a start point, then six numbers per cubic Bézier
    /// (two control points and the end point), closing back on the start.
    static let outlineData: [[Double]] = [
${strokes.map((s) => `        [\n${rows(s.values, 8, '            ')}\n        ],`).join('\n')}
    ]

    /// Each stroke's brush spine, top to tip, as x,y pairs.
    static let spineData: [[Double]] = [
${strokes.map((s) => `        [\n${rows(s.spine, 8, '            ')}\n        ],`).join('\n')}
    ]

    /// The ink's bounding box.
    static let box = CGRect(x: ${n(x0)}, y: ${n(y0)}, width: ${n(Math.round((x1 - x0) * 10) / 10)}, height: ${n(Math.round((y1 - y0) * 10) / 10)})

    /// The point placed at a frame's centre: halfway between the box's centre and the ink's
    /// centroid, on both axes (docs/design/studies/kawa/kawa-centering-r1.html).
    static let centre = Point(${n(data.point[0])}, ${n(data.point[1])})
}
`);
